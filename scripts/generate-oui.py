#!/usr/bin/env python3
"""Builds src/domain/data/oui.ts from the IEEE MA-L (OUI) registry.

Usage:
    curl -L -o oui.csv https://standards-oui.ieee.org/oui/oui.csv
    python scripts/generate-oui.py oui.csv

Vendor names are shortened ("TP-LINK TECHNOLOGIES CO.,LTD." -> "TP-Link") and
stored once; the table maps each 24-bit prefix to a vendor index. The output
is sorted so the app can binary-search it.
"""
import csv
import re
import sys
from collections import Counter
from datetime import date

SUFFIXES = re.compile(
    r"[\s,.]*\b("
    r"co|company|corp|corporation|inc|incorporated|ltd|limited|llc|l\.l\.c|gmbh|ag|kg|"
    r"s\.?a|s\.?a\.?s|s\.?p\.?a|s\.?r\.?l|b\.?v|n\.?v|oy|ab|a/s|asa|as|pty|plc|sa de cv|"
    r"technologies|technology|tech|electronics|electronic|international|intl|holdings|"
    r"group|industrial|industries|enterprise|enterprises|systems|communications|"
    r"communication|telecommunications|telecom|network|networks|products|manufacturing|"
    r"science|sciences|digital|semiconductor|devices|solutions|computer|mobile|"
    r"shenzhen|guangdong|beijing|shanghai|hangzhou|zhejiang|jiangsu|xiamen|dongguan"
    r")\b\.?\s*$",
    re.IGNORECASE,
)
LEADING_CITY = re.compile(
    r"^(shenzhen|guangdong|beijing|shanghai|hangzhou|zhejiang|jiangsu|xiamen|dongguan|"
    r"suzhou|qingdao|chengdu|wuhan|fujian|ningbo|tianjin)\s+",
    re.IGNORECASE,
)


# Registry names that differ from the brand people know.
ALIASES = {
    "AVM Audiovisuelles Marketing und Compute": "AVM (FRITZ!)",
    "Routerboard.com": "MikroTik",
    "Raspberry Pi Trading": "Raspberry Pi",
    "Raspberry Pi Foundation": "Raspberry Pi",
    "Hon Hai Precision Ind": "Foxconn",
    "Intel Corporate": "Intel",
    "Motorola Mobility LLC, a Lenovo": "Motorola",
    "Hewlett Packard": "HP",
    "ASUSTek": "ASUS",
}
# Blocks the IEEE split into smaller (MA-M / MA-S) assignments: no single vendor.
SKIP = {"IEEE Registration Authority", "Private"}


def short_name(name: str) -> str:
    name = re.sub(r"\(.*?\)", "", name).replace(" ", " ")
    name = re.sub(r"\s+", " ", name).strip(" ,.-")
    previous = None
    while previous != name:
        previous = name
        name = SUFFIXES.sub("", name).strip(" ,.-&")
        stripped = LEADING_CITY.sub("", name)
        if stripped:
            name = stripped
    if not name:
        return previous or ""
    if name.upper() == name:
        # SHOUTING → Title case, but keep short acronyms (ZTE, TP, AVM).
        name = re.sub(
            r"[A-Z]{4,}",
            lambda m: m.group(0).capitalize(),
            name,
        )
    if name.islower() and len(name) <= 3:
        name = name.upper()  # zte → ZTE
    return name[:40].replace("|", "/")


def main(path: str) -> None:
    rows = []
    with open(path, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            if row["Registry"] != "MA-L":
                continue
            prefix = row["Assignment"].strip().upper()
            if not re.fullmatch(r"[0-9A-F]{6}", prefix):
                continue
            vendor = short_name(row["Organization Name"])
            vendor = ALIASES.get(vendor, vendor)
            if vendor and vendor not in SKIP:
                rows.append((prefix, vendor))
    rows.sort()
    counts = Counter(vendor for _, vendor in rows)
    vendors = [vendor for vendor, _ in counts.most_common()]
    index = {vendor: i for i, vendor in enumerate(vendors)}
    assert len(vendors) < 36**3

    def base36(value: int) -> str:
        digits = "0123456789abcdefghijklmnopqrstuvwxyz"
        out = ""
        for _ in range(3):
            out = digits[value % 36] + out
            value //= 36
        return out

    table = "".join(prefix + base36(index[vendor]) for prefix, vendor in rows)
    with open("src/domain/data/oui.ts", "w", encoding="utf-8", newline="\n") as out:
        out.write(
            "/* eslint-disable */\n"
            "// prettier-ignore\n"
            f"// Generated by scripts/generate-oui.py from the IEEE MA-L registry ({date.today().isoformat()}).\n"
            "// Source: https://standards-oui.ieee.org/oui/oui.csv — do not edit by hand.\n\n"
            f"/** Short vendor names, most common first, separated by `|`. */\n"
            f"export const OUI_VENDORS = {json_string('|'.join(vendors))};\n\n"
            "/** Sorted 9-character entries: 6 hex digits of the prefix + base-36 vendor index. */\n"
            f"export const OUI_TABLE = {json_string(table)};\n"
        )
    print(f"{len(rows)} prefixes, {len(vendors)} vendors, {len(table) // 1024} KB table")


def json_string(value: str) -> str:
    import json

    return json.dumps(value, ensure_ascii=False)


if __name__ == "__main__":
    main(sys.argv[1])
